function unpack(packed) {
  const bytes = Buffer.from(packed.data, "base64");
  if (packed.encoding === "gzip-base64-utf8-json") {
    return JSON.parse(gunzipSync(bytes).toString("utf8"));
  }
  assert.equal(packed.encoding, "lzw16le-base64-utf8-json");
  const dictionary = Array.from({ length: 256 }, (_, index) => String.fromCharCode(index));
  const codes = [];
  for (let index = 0; index < bytes.length; index += 2) codes.push(bytes.readUInt16LE(index));
  let previous = dictionary[codes.shift()];
  let binary = previous;
  for (const code of codes) {
    const current = dictionary[code] ?? previous + previous[0];
    binary += current;
    if (dictionary.length < 65536) dictionary.push(previous + current[0]);
    previous = current;
  }
  return JSON.parse(Buffer.from(binary, "latin1").toString("utf8"));
}

function sanitizeArticle(html) {
  const result = sanitizeHtmlWithReport(html.replace(/<(\/?)h1\b/gi, "<$1h2"));
  assert.equal(result.report.blockedUrls, 0);
  assert.deepEqual(result.report.removedDangerousElements, {});
  assert.deepEqual(result.report.removedTags, {});
  assert.deepEqual(result.report.removedAttributes, {});
  assert.equal(result.report.autoClosedTags, 0);
  // The existing sanitizer escapes already escaped attribute entities a second
  // time. Restore exactly one layer in attributes generated by our renderer.
  return result.html.replace(
    /(href|src|alt|title)="([^"]*)"/g,
    (_, attribute, value) =>
      attribute + '="' + value.replace(/&amp;(amp|quot|lt|gt|#39);/g, "&$1;") + '"',
  );
}

