const transfers = (await readdir(inputDirectory))
  .filter((name) => /^page-\d{2}-\d{2}\.json$/.test(name))
  .sort();
const posts = [];
const audits = [];
for (const filename of transfers) {
  const transfer = JSON.parse(await readFile(path.join(inputDirectory, filename), "utf8"));
  const page = unpack(transfer.packed);
  assert.equal(page.posts.length, transfer.end - transfer.start);
  if (transfer.start === 0) audits.push(page.audit);
  posts.push(...page.posts);
}
