const groups = new Map();
for (const post of posts) {
  if (!post.translationId) continue;
  const members = groups.get(post.translationId) || [];
  members.push(post);
  groups.set(post.translationId, members);
}
for (const members of groups.values()) {
  assert.equal(new Set(members.map((post) => post.language)).size, members.length);
}

const sumAudit = (key) => audits.reduce((sum, audit) => sum + (audit[key] || 0), 0);
const mergeAudit = (key) => {
  const combined = {};
  for (const audit of audits)
    for (const [name, count] of Object.entries(audit[key] || {}))
      combined[name] = (combined[name] || 0) + count;
  return combined;
};
const plain = (html) =>
  html
    .replace(/<[^>]+>/g, " ")
    .replace(/\s+/g, " ")
    .trim();
const identicalBodyPairs = [];
for (const [translationId, members] of groups) {
  for (let left = 0; left < members.length; left += 1) {
    for (let right = left + 1; right < members.length; right += 1) {
      if (plain(members[left].html) === plain(members[right].html)) {
        identicalBodyPairs.push({
          translationId,
          languages: [members[left].language, members[right].language],
          postIds: [members[left].id, members[right].id],
        });
      }
    }
  }
}
const editorialReview = [];
for (const post of posts) {
  const text = plain(post.html);
  const signals = [];
  if (
    /vize memuru|visa officer|visumbeam|funcionario de visado|funzionario.*visti/i.test(
      post.title + " " + text,
    )
  )
    signals.push("visa-officer-persona-or-framing");
  if (
    /monetization|passive income|side income|guaranteed|garantili|kesin kabul|100% success/i.test(
      post.title + " " + text,
    )
  )
    signals.push("earnings-or-outcome-claim");
  if (signals.length) editorialReview.push({ postId: post.id, language: post.language, signals });
}

