assert.equal(new Set(posts.map((post) => post.id)).size, 710);
assert.equal(new Set(posts.map((post) => post.language + "/" + post.slug)).size, 710);

for (const post of posts) {
  const source = metadataById.get(post.id);
  assert.ok(source, "Every body must match an exact source post ID.");
  assert.equal(post.language, source.language);
  post.translationId = source.translationId;
  assert.ok(post.title.trim());
  assert.ok(post.slug.trim());
  assert.ok(post.html.trim(), "Every exported article needs its full body.");
  assert.ok(/^\d{4}-\d{2}-\d{2}T/.test(post.publishedAt));
  assert.ok(/^\d{4}-\d{2}-\d{2}T/.test(post.updatedAt));
  assert.equal(new URL(post.sourceUrl).hostname, "www.anilgoktas.org");
  post.html = sanitizeArticle(post.html);
  assert.doesNotMatch(post.html, /<h1\b|<script\b|<iframe\b|\bon\w+\s*=|javascript:/i);
  assert.ok(
    !("contactId" in post) && !("memberId" in post) && !("mostRecentContributorId" in post),
  );
}
