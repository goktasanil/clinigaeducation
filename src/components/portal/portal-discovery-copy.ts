export function getPortalDiscoveryCopy(locale: string): PortalDiscoveryCopy {
  const language = locale.toLowerCase().split("-")[0] as LanguageCode;
  return Object.prototype.hasOwnProperty.call(COPY, language) ? COPY[language] : COPY.tr;
}

export function usePortalDiscoveryCopy(): PortalDiscoveryCopy {
  const { i18n } = useTranslation();
  return getPortalDiscoveryCopy(i18n.resolvedLanguage || i18n.language || "tr");
}

export function formatPortalDiscoveryCopy(
  copy: PortalDiscoveryCopy,
  key: keyof PortalDiscoveryCopy,
  values: Record<string, string | number> = {},
): string {
  return copy[key].replace(/\{\{(\w+)\}\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match,
  );
}
